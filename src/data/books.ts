/**
 * Every book points at its real cover on Open Library. `default=false` makes the
 * endpoint return a 404 when no cover exists, which lets `BookCover` fall back to
 * the generated SVG art below instead of a broken image.
 */
function openLibraryCover(isbn: string): string {
  return `https://covers.openlibrary.org/b/isbn/${isbn}-L.jpg?default=false`;
}

export const BOOKS: Book[] = BOOK_SEEDS.map(({ isbn, ...book }) => ({
  ...book,
  coverImage: openLibraryCover(isbn),
}));

export const AUTHOR_MAP = new Map(AUTHORS.map((a) => [a.id, a]));

export function booksByAuthor(authorId: string): Book[] {
  return BOOKS.filter((b) => b.authorId === authorId);
}

export function getBook(id: string): Book | undefined {
  return BOOKS.find((b) => b.id === id);
}
